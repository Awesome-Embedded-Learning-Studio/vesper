#!/usr/bin/env python3
"""Build han16.bdf, the desktop's CJK subset, from GNU Unifont's full BDF.

Input: the unifont-17.0.03 BDF (https://unifoundry.com/pub/unifont/), which
carries SIL OFL 1.1 / GPLv2+ with the font embedding exception. This script
keeps only the glyphs the desktop needs -- the 3500 level-1 characters of the
Table of General Standard Chinese Characters plus a small set of CJK
punctuation -- and re-emits them as one sorted BDF for visor's fontgen.

Usage: make_han16.py <unifont.bdf> <level1.txt> <out.bdf>
"""

import sys

# CJK punctuation and symbols worth carrying next to the hanzi: the terminal
# prints text that uses these, and a font without them draws holes where the
# sentence's commas should be.
EXTRA_CHARS = "，。、：；！？（）【】《》“”‘’—…·×÷"


def wanted_codepoints(level1_path: str) -> list[int]:
    chars = set(EXTRA_CHARS)
    with open(level1_path, encoding="utf-8") as handle:
        chars.update(handle.read().split())
    return sorted(ord(ch) for ch in chars)


def main() -> int:
    unifont_path, level1_path, out_path = sys.argv[1:4]
    wanted = set(wanted_codepoints(level1_path))

    glyphs: dict[int, list[str]] = {}
    current_encoding: int | None = None
    current_lines: list[str] = []
    with open(unifont_path, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            if line.startswith("STARTCHAR"):
                current_lines = [line]
                current_encoding = None
            elif current_lines:
                current_lines.append(line)
                if line.startswith("ENCODING"):
                    current_encoding = int(line.split()[1])
                elif line.startswith("ENDCHAR"):
                    if current_encoding in wanted:
                        glyphs[current_encoding] = current_lines
                    current_lines = []
                    current_encoding = None

    missing = wanted - set(glyphs)
    if missing:
        print(f"make_han16: {len(missing)} codepoints missing from unifont, "
              f"e.g. U+{min(missing):04X}", file=sys.stderr)

    with open(out_path, "w", encoding="utf-8") as out:
        out.write("STARTFONT 2.1\n")
        out.write("FONT -gnu-Unifont-CJK-Han16-Medium-R-Normal--16-160-75-75-c-80-iso10646-1\n")
        out.write("SIZE 16 75 75\n")
        out.write("FONTBOUNDINGBOX 16 16 0 -2\n")
        out.write("COMMENT Generated by scripts/fonts/make_han16.py from GNU Unifont 17.0.03.\n")
        out.write("COMMENT Source font: SIL OFL 1.1 / GPLv2+ with font embedding exception.\n")
        out.write("COMMENT Hanzi set: level-1 Table of General Standard Chinese Characters.\n")
        out.write("STARTPROPERTIES 2\n")
        out.write("FONT_ASCENT 14\n")
        out.write("FONT_DESCENT 2\n")
        out.write("ENDPROPERTIES\n")
        out.write(f"CHARS {len(glyphs)}\n")
        for encoding in sorted(glyphs):
            name = f"uni{encoding:04X}"
            out.write(f"STARTCHAR {name}\n")
            for line in glyphs[encoding]:
                if line.startswith(("STARTCHAR", "ENDCHAR")):
                    continue  # re-emitted with our own name
                out.write(line)
            out.write("ENDCHAR\n")
    print(f"make_han16: wrote {len(glyphs)} glyphs to {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
