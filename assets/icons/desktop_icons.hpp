// The desk's two icons as layered art: each icon is two one-bit bitmaps of
// the same 24x24 cell painted one over the other, each layer in its own
// ink -- the window reads as a gold frame with ink glass and buttons, the
// terminal as a muted body with a gold prompt and stand. Layering keeps the
// mono-bitmap pipeline (fonts, wallpaper, draw_bitmap) untouched: color
// art is the same bitmaps wearing different inks, not a new asset format.
// One byte per eight pixels, MSB first, three bytes per row -- the canvas
// packing -- and the comment beside each row is the picture itself, so a
// change is a diff of dots.

